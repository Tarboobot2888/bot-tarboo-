#!/usr/bin/env node
// ═══════════════════════════════════════════════
// ☁️ يولّد docs/terboo-vps-permissions.json من كتالوج قدرات Terboo VPS (مصدر واحد للحقيقة)
//   node tools/terboo-vps-matrix.mjs
// ═══════════════════════════════════════════════

import fs from "node:fs";
import path from "node:path";

const { permissionMatrix, userSafeActions, ownerActions, sensitiveActions } = await import("../src/lib/providers/virtualizor/virtualizor-capabilities.js");
const out = {
  $comment: "Generated by tools/terboo-vps-matrix.mjs from src/lib/providers/virtualizor/virtualizor-capabilities.js — do not edit by hand.",
  model: "Buyer → canonical identity → active entitlement → owns this vpsId → action policy (confirmation, private chat, rate limit) → provider capability → Virtualizor API. Admin layer (4085) is owner-only and never used for a buyer.",
  userSafeActions: userSafeActions(),
  ownerActions: ownerActions(),
  sensitiveActions: sensitiveActions(),
  actions: permissionMatrix(),
};
const file = path.join(process.cwd(), "docs", "terboo-vps-permissions.json");
fs.writeFileSync(file, `${JSON.stringify(out, null, 2)}\n`);
console.log(`✅ ${path.relative(process.cwd(), file)}: ${out.actions.length} actions`);
