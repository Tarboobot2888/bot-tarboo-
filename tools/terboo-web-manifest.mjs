#!/usr/bin/env node
// ═══════════════════════════════════════════════
// 🔒 بصمة ملفات الموقع — حارس نطاق «لا تعديل على web/»
// ───────────────────────────────────────────────
//   node tools/terboo-web-manifest.mjs           ← يسجّل البصمات
//   node tools/terboo-web-manifest.mjs --check    ← يفشل إن تغيّر أي ملف
//
// نطاق مهمة ألعاب Mini Apps يمنع تعديل أي ملف تحت web/. البصمة تحوّل هذا
// الشرط من وعد في تقرير إلى فحص يفشل آلياً.
// ═══════════════════════════════════════════════

import { execFileSync } from "node:child_process";
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const OUT = path.join(ROOT, "docs", "v6", "web-files-sha256.json");
const CHECK = process.argv.includes("--check");

/**
 * قائمة ملفات web/.
 * git هو المصدر عند توفره (يحترم .gitignore)، وإلا نمشي على المجلد — فالحارس
 * يعمل أيضاً داخل حزمة مفكوكة بلا مستودع، وهي الحالة التي يشغّله فيها المالك.
 */
function webFiles() {
  try {
    const tracked = execFileSync("git", ["ls-files", "-z", "web/"], { cwd: ROOT, stdio: ["ignore", "pipe", "ignore"] })
      .toString("utf8").split("\0").filter(Boolean);
    if (tracked.length) return tracked.sort();
  } catch { /* لا مستودع: نمشي على المجلد */ }
  const out = [];
  const walk = (rel) => {
    const abs = path.join(ROOT, rel);
    if (!fs.existsSync(abs)) return;
    for (const entry of fs.readdirSync(abs, { withFileTypes: true })) {
      const next = path.posix.join(rel, entry.name);
      if (entry.isDirectory()) walk(next);
      else if (entry.isFile()) out.push(next);
    }
  };
  walk("web");
  return out.sort();
}

const files = webFiles();
if (!files.length) {
  console.error("❌ لا ملفات تحت web/ — البصمة بلا معنى");
  process.exit(2);
}

const entries = {};
for (const file of files) {
  const abs = path.join(ROOT, file);
  if (!fs.existsSync(abs)) {
    console.error(`❌ ملف متتبَّع مفقود من الشجرة: ${file}`);
    process.exit(1);
  }
  entries[file] = crypto.createHash("sha256").update(fs.readFileSync(abs)).digest("hex");
}
const manifest = { $comment: "Generated by tools/terboo-web-manifest.mjs — WEB_FILES_UNCHANGED guard.", files: entries.length, count: files.length, sha256: entries };
const text = `${JSON.stringify(manifest, null, 1)}\n`;

if (!CHECK) {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, text);
  console.log(`🔒 ${files.length} ملف تحت web/ · بصماتها في ${path.relative(ROOT, OUT)}`);
  process.exit(0);
}

if (!fs.existsSync(OUT)) {
  console.error(`❌ لا بصمة مسجّلة (${path.relative(ROOT, OUT)}) — شغّل الأداة بلا --check أولاً`);
  process.exit(1);
}
const saved = JSON.parse(fs.readFileSync(OUT, "utf8")).sha256 || {};
const changed = files.filter((f) => saved[f] !== entries[f]);
const added = files.filter((f) => !(f in saved));
const removed = Object.keys(saved).filter((f) => !(f in entries));

if (changed.length || added.length || removed.length) {
  console.error("❌ WEB_FILES_UNCHANGED: FAIL");
  for (const f of changed) console.error(`   تغيّر: ${f}`);
  for (const f of added) console.error(`   أُضيف: ${f}`);
  for (const f of removed) console.error(`   حُذف: ${f}`);
  process.exit(1);
}
console.log(`✅ WEB_FILES_UNCHANGED: PASS · ${files.length} ملف بلا تغيير`);
